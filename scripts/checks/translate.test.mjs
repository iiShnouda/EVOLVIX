import { login, check, eq, ok, summary } from './lib.mjs';
const tag = Date.now().toString(36).slice(-5);
const owner = await login('owner@skb.local');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const unit = ok('AR-only unit', await owner.post('/units', { nameAr: `بالتة ${tag}` }));
const level = ok('EN-only level', await owner.post('/price-levels', { side: 'SALE', nameEn: `Half wholesale ${tag}` }));
const color = ok('AR-only color', await owner.post('/variant-options', { kind: 'COLOR', nameAr: `زيتي ${tag}` }));
const size = ok('EN-only size', await owner.post('/variant-options', { kind: 'SIZE', nameEn: `Big ${tag}` }));
const cat = (await owner.get('/categories')).data[0];
const piece = (await owner.get('/units')).data.find((u) => u.names.en === 'Piece');
const model = ok('EN-only model', await owner.post('/models', { nameEn: `Jacket ${tag}`, code: `JK${tag}`, categoryId: cat.id, sizeIds: [size.id], colorIds: [color.id], units: [{ unitId: piece.id, factor: 1 }] }));
const v0 = model.variants[0];
check('variant EN composed (colour as typed or already translated)', [`Jacket ${tag} — زيتي ${tag} / Big ${tag}`, `Jacket ${tag} — E زيتي ${tag} / Big ${tag}`].includes(v0.name), v0.name);
let status;
for (let i = 0; i < 30; i++) { await wait(1000); status = (await owner.get('/settings/translation')).data; if (status.pending === 0) break; }
eq('everything translated', status.pending, 0);
const units = (await owner.get('/units')).data;
eq('unit translated to EN', units.find((u) => u.id === unit.id).names.en, `E بالتة ${tag}`);
const lv = (await owner.get('/price-levels')).data.find((l) => l.id === level.id);
eq('level translated to AR', [lv.names.ar, lv.names.auto], [`ع Half wholesale ${tag}`, 'ar']);
const m = (await owner.get(`/models/${model.id}`)).data;
eq('variant EN recomposed after translation', m.variants[0].name, `Jacket ${tag} — E زيتي ${tag} / Big ${tag}`);
const mAr = (await owner.lang('ar').get(`/models/${model.id}`)).data;
eq('variant AR recomposed', mAr.variants[0].name, `ع Jacket ${tag} — زيتي ${tag} / ع Big ${tag}`);
const p = (await owner.get(`/products/${v0.productId}`)).data;
eq('variant not queued itself', p.names.pending, false);
process.exit(summary('translation') ? 1 : 0);
