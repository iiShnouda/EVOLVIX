export function permissionsForRole(role: Role): Permission[] {
  return ROLE_PERMISSIONS[role] ?? [];
}

export function roleHasPermission(role: Role, permission: Permission): boolean {
  return permissionsForRole(role).includes(permission);
}

export function hasPermission(userPermissions: Permission[], permission: Permission): boolean {
  return userPermissions.includes(permission);
}

/** Whether the person holds any of these. */
export function hasAnyPermission(userPermissions: Permission[], wanted: Permission[]): boolean {
  return wanted.some((p) => userPermissions.includes(p));
}
